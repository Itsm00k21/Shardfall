#!/bin/sh
# Writes src/ReplicatedStorage/Shared/BuildStamp.luau with the real git
# short sha, so Output and the HUD say exactly which commit Rojo serves.
# "+" means the working tree had uncommitted edits when this ran.
# The file is gitignored. Rojo picks it up like any other module.
# Run by hand, or install the git hooks once: sh scripts/install-hooks.sh
set -e
root=$(git rev-parse --show-toplevel)
cd "$root"
sha=$(git rev-parse --short=7 HEAD)
branch=$(git rev-parse --abbrev-ref HEAD)
dirty=""
if [ -n "$(git status --porcelain --untracked-files=no -- src)" ]; then
	dirty="+"
fi
at=$(date "+%Y-%m-%d %H:%M %Z")
out="src/ReplicatedStorage/Shared/BuildStamp.luau"
tmp="$out.tmp"
cat > "$tmp" <<LUA
--!strict
-- Generated by scripts/stamp.sh. Do not edit. Gitignored.
return {
	sha = "$sha$dirty",
	branch = "$branch",
	at = "$at",
}
LUA
mv "$tmp" "$out"
echo "[stamp] $sha$dirty $branch $at"
